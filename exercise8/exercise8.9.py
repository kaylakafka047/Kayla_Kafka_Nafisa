def show_messages(messages):
    """Mencetak setiap pesan dalam list."""
    for message in messages:
        print(message)

text_messages = [
    "Halo, apa kabar?",
    "Jangan lupa kerjakan tugas coding.",
    "Python sangat menyenangkan!",
    "Sampai jumpa besok."
]

show_messages(text_messages)