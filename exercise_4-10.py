favorite_pizzas = [
    "Pepperoni",
    "Cheese",
    "Beef",
    "Mushroom",
    "Tuna",
    "Chicken",
    "Vegetarian"
]

# Menampilkan tiga pizza pertama
print("The first three items in the list are:")
print(favorite_pizzas[:3])

# Menampilkan tiga pizza dari bagian tengah
print("\nThree items from the middle of the list are:")
print(favorite_pizzas[2:5])

# Menampilkan tiga pizza terakhir
print("\nThe last three items in the list are:")
print(favorite_pizzas[-3:])